"""Bounded, text-only inspection of explicitly supplied slides and PDFs.

Archives are never extracted. Images, notes, layout, scripts, links and embedded
objects are not interpreted. PDF parsing runs in an isolated, timed process.
"""

from __future__ import annotations

from importlib.util import find_spec
import io
import json
import os
from pathlib import Path, PurePosixPath
import posixpath
import re
import stat
import subprocess
import sys
import xml.etree.ElementTree as ET
import zipfile
import zlib


MAX_INPUT_BYTES = 10 * 1024 * 1024
MAX_TEXT_CHARS = 24_000
MAX_PAGES = 100
MAX_ZIP_MEMBERS = 2_048
MAX_ZIP_EXPANDED_BYTES = 32 * 1024 * 1024
MAX_XML_BYTES = 2 * 1024 * 1024
MAX_TOTAL_XML_BYTES = 8 * 1024 * 1024
MAX_COMPRESSION_RATIO = 200
PDF_TIMEOUT_SECONDS = 15
SLIDE_PART = re.compile(r"ppt/slides/slide([0-9]+)\.xml\Z")
UNSAFE_XML = re.compile(r"<!\s*(?:DOCTYPE|ENTITY)\b", re.IGNORECASE)
DRAWING_NS = "{http://schemas.openxmlformats.org/drawingml/2006/main}"
PRESENTATION_NS = "{http://schemas.openxmlformats.org/presentationml/2006/main}"
RELATIONSHIP_NS = "{http://schemas.openxmlformats.org/officeDocument/2006/relationships}"

PPTX_LIMITATIONS = [
    "PPTX inspection includes slide text only; images, charts, speaker notes, "
    "animations, embedded objects and visual layout are unanalysed.",
    "PPTX text order follows the XML structure and may differ from visual reading order.",
]
PDF_LIMITATIONS = [
    "PDF inspection includes extractable text only; images, video, audio, embedded "
    "objects and visual layout are unanalysed. Scanned/image-only pages are not OCRed.",
    "PDF text order may differ from visual reading order.",
]


def _result(text: str | None, limitations: list[str], truncated: bool = False) -> dict:
    return {"text": text, "limitations": limitations, "truncated": truncated}


def _unsafe_file(info: os.stat_result) -> bool:
    attributes = getattr(info, "st_file_attributes", 0)
    return (
        not stat.S_ISREG(info.st_mode)
        or bool(attributes & getattr(stat, "FILE_ATTRIBUTE_REPARSE_POINT", 0x400))
        or bool(attributes & getattr(stat, "FILE_ATTRIBUTE_HIDDEN", 0x2))
    )


def _identity(info: os.stat_result) -> tuple[int, int]:
    return info.st_dev, info.st_ino


def _read_attachment(path: Path, expected_stat: os.stat_result | None) -> bytes:
    before = path.lstat()
    if _unsafe_file(before):
        raise ValueError("Attachment must be a regular, non-hidden file without links.")
    if expected_stat is not None and _identity(before) != _identity(expected_stat):
        raise ValueError("Attachment changed after its safety check; no text was read.")
    if before.st_size > MAX_INPUT_BYTES:
        raise ValueError("Attachment exceeds the 10 MiB input limit and was not read.")
    flags = os.O_RDONLY | getattr(os, "O_BINARY", 0) | getattr(os, "O_NOFOLLOW", 0)
    descriptor = os.open(path, flags)
    with os.fdopen(descriptor, "rb") as stream:
        opened = os.fstat(stream.fileno())
        current = path.lstat()
        if (
            _unsafe_file(opened) or _unsafe_file(current)
            or _identity(opened) != _identity(before)
            or _identity(current) != _identity(before)
            or opened.st_size > MAX_INPUT_BYTES
        ):
            raise ValueError("Attachment changed before reading; no text was read.")
        data = stream.read(MAX_INPUT_BYTES + 1)
        after = os.fstat(stream.fileno())
        final = path.lstat()
        if (
            _identity(final) != _identity(before) or _unsafe_file(final)
            or (opened.st_size, opened.st_mtime_ns) != (after.st_size, after.st_mtime_ns)
            or (after.st_size, after.st_mtime_ns) != (final.st_size, final.st_mtime_ns)
        ):
            raise ValueError("Attachment changed during reading; its text was discarded.")
    if len(data) > MAX_INPUT_BYTES:
        raise ValueError("Attachment exceeds the 10 MiB input limit; its text was discarded.")
    return data


def _xml(data: bytes) -> ET.Element:
    # Restrict to UTF-8 before the declaration check so UTF-16 cannot hide DTDs
    # behind NUL bytes. OOXML generated by normal exporters uses UTF-8.
    decoded = data.decode("utf-8-sig", errors="strict")
    if UNSAFE_XML.search(decoded):
        raise ValueError("PPTX XML declarations containing DTDs/entities are not supported.")
    return ET.fromstring(decoded)


def _extract_pptx(data: bytes, max_chars: int) -> dict:
    limitations = list(PPTX_LIMITATIONS)
    output: list[str] = []
    used = 0
    truncated = False
    with zipfile.ZipFile(io.BytesIO(data)) as archive:
        members = archive.infolist()
        if len(members) > MAX_ZIP_MEMBERS:
            raise ValueError("PPTX exceeds the archive member limit and is unanalysed.")
        seen: set[str] = set()
        expanded = 0
        for member in members:
            name = member.filename
            if (
                name in seen or "\\" in name or name.startswith("/")
                or ".." in PurePosixPath(name).parts or ":" in name
            ):
                raise ValueError("PPTX contains ambiguous or unsafe archive paths.")
            seen.add(name)
            expanded += member.file_size
            if expanded > MAX_ZIP_EXPANDED_BYTES:
                raise ValueError("PPTX exceeds the expanded archive size limit.")
            if member.flag_bits & 1:
                raise ValueError("Encrypted PPTX archives are not supported.")
            if member.file_size > max(1, member.compress_size) * MAX_COMPRESSION_RATIO:
                raise ValueError("PPTX exceeds the archive compression ratio limit.")
        parts = [name for name in seen if SLIDE_PART.fullmatch(name)]
        parts.sort(key=lambda name: (int(SLIDE_PART.fullmatch(name).group(1)), name))
        if not parts:
            raise ValueError("PPTX contains no supported slide XML parts.")
        xml_bytes = 0

        def read_xml(name: str) -> ET.Element:
            nonlocal xml_bytes
            member = archive.getinfo(name)
            if member.file_size > MAX_XML_BYTES:
                raise ValueError("PPTX XML part exceeds the per-part size limit.")
            if xml_bytes + member.file_size > MAX_TOTAL_XML_BYTES:
                raise ValueError("PPTX XML parts exceed the combined size limit.")
            if member.compress_type not in (zipfile.ZIP_STORED, zipfile.ZIP_DEFLATED):
                raise ValueError("PPTX uses an unsupported XML compression format.")
            with archive.open(member) as stream:
                raw = stream.read(MAX_XML_BYTES + 1)
            if len(raw) > MAX_XML_BYTES:
                raise ValueError("PPTX XML part exceeds the read limit.")
            xml_bytes += len(raw)
            return _xml(raw)

        presentation = "ppt/presentation.xml"
        relationships = "ppt/_rels/presentation.xml.rels"
        if presentation in seen and relationships in seen:
            tree = read_xml(presentation)
            relation_tree = read_xml(relationships)
            targets = {}
            for relation in relation_tree:
                if relation.get("TargetMode", "").casefold() == "external":
                    continue
                target = relation.get("Target", "")
                if "\\" in target or ":" in target:
                    continue
                normal = posixpath.normpath(
                    target.lstrip("/") if target.startswith("/") else "ppt/" + target
                )
                if normal in parts:
                    targets[relation.get("Id")] = normal
            ordered = [
                targets.get(slide.get(RELATIONSHIP_NS + "id"))
                for slide in tree.iter(PRESENTATION_NS + "sldId")
            ]
            # An inconsistent relationship map must not silently omit slides.
            if ordered and len(ordered) == len(parts) and set(ordered) == set(parts):
                parts = ordered
            else:
                limitations.append("PPTX slide ordering metadata is incomplete; numeric part order was used.")
        if len(parts) > MAX_PAGES:
            limitations.append("Only the first 100 PPTX slides were inspected.")
            truncated = True
        for index, name in enumerate(parts[:MAX_PAGES], 1):
            root = read_xml(name)
            paragraphs = []
            for paragraph in root.iter(DRAWING_NS + "p"):
                fragments = []
                for node in paragraph.iter():
                    if node.tag == DRAWING_NS + "t" and node.text:
                        fragments.append(node.text)
                    elif node.tag == DRAWING_NS + "br":
                        fragments.append("\n")
                if fragments:
                    paragraphs.append("".join(fragments))
            # Tolerate minimal exported parts without paragraph wrappers.
            if not paragraphs:
                paragraphs = [node.text for node in root.iter(DRAWING_NS + "t") if node.text]
            chunk = f"[Slide {index}]\n" + "\n".join(paragraphs) + "\n"
            remaining = max_chars - used
            output.append(chunk[:remaining])
            used += min(len(chunk), remaining)
            if len(chunk) > remaining or (used == max_chars and index < len(parts)):
                truncated = True
                break
    if truncated:
        limitations.append("Slide evidence was truncated by the page or character limit.")
    return _result("".join(output), limitations, truncated)


def _extract_pdf_data(data: bytes, max_chars: int) -> dict:
    """Worker implementation; never called on untrusted PDFs in the main process."""
    limitations = list(PDF_LIMITATIONS)
    try:
        from pypdf import PdfReader
        from pypdf import filters
        # Bound common FlateDecode decompression independently of compressed
        # input size. The process timeout also covers malformed page trees.
        filters.ZLIB_MAX_OUTPUT_LENGTH = 8 * 1024 * 1024
        reader = PdfReader(io.BytesIO(data), strict=True)
        if reader.is_encrypted:
            return _result(None, limitations + ["Encrypted PDFs are not supported."])
        count = len(reader.pages)
        truncated = count > MAX_PAGES
        output: list[str] = []
        used = 0
        empty_pages = 0
        for index in range(min(count, MAX_PAGES)):
            text = reader.pages[index].extract_text() or ""
            if not text.strip():
                empty_pages += 1
            chunk = f"[Page {index + 1}]\n{text}\n"
            remaining = max_chars - used
            output.append(chunk[:remaining])
            used += min(len(chunk), remaining)
            if len(chunk) > remaining or (used == max_chars and index + 1 < count):
                truncated = True
                break
        if empty_pages:
            limitations.append("Some PDF pages contain no extractable text; image-only content is unanalysed.")
        if truncated:
            limitations.append("PDF evidence was truncated by the 100-page or character limit.")
        return _result("".join(output), limitations, truncated)
    except ImportError:
        return _result(None, limitations + ["PDF text extraction needs pypdf: run python -m pip install pypdf."])
    except Exception:
        return _result(None, limitations + ["PDF text could not be safely extracted; provide a text export."])


def _extract_pdf(data: bytes, max_chars: int) -> dict:
    if find_spec("pypdf") is None:
        return _result(None, list(PDF_LIMITATIONS) + [
            "PDF text extraction needs pypdf: run python -m pip install pypdf.",
        ])
    try:
        process = subprocess.run(
            [sys.executable, "-I", str(Path(__file__).resolve()), "--pdf-worker", str(max_chars)],
            input=data, stdout=subprocess.PIPE, stderr=subprocess.DEVNULL,
            timeout=PDF_TIMEOUT_SECONDS, check=False,
        )
        if process.returncode != 0 or len(process.stdout) > max_chars * 4 + 16_384:
            raise ValueError("Invalid PDF worker response")
        result = json.loads(process.stdout)
        if (
            not isinstance(result, dict) or not isinstance(result.get("limitations"), list)
            or not isinstance(result.get("truncated"), bool)
            or not (result.get("text") is None or isinstance(result.get("text"), str))
        ):
            raise ValueError("Invalid PDF worker response")
        if result["text"] is not None and len(result["text"]) > max_chars:
            raise ValueError("Unbounded PDF worker response")
        return result
    except subprocess.TimeoutExpired:
        return _result(None, list(PDF_LIMITATIONS) + ["PDF extraction exceeded its 15-second time limit."])
    except (OSError, ValueError, UnicodeDecodeError):
        return _result(None, list(PDF_LIMITATIONS) + ["PDF extraction worker failed; provide a text export."])


def extract_attachment(
    path: Path, max_chars: int = MAX_TEXT_CHARS, *, expected_stat: os.stat_result | None = None,
) -> dict:
    """Return inert text and explicit omissions; never follow or expand files.

    ``expected_stat`` binds the read to the file the bundle collector validated.
    Unsupported, malformed or over-limit files produce ``text=None``.
    """
    path = Path(path)
    limit = max(0, min(int(max_chars), MAX_TEXT_CHARS))
    if limit == 0:
        return _result(None, ["No attachment character budget remains."], True)
    extension = path.suffix.casefold()
    if extension not in {".pptx", ".pdf"}:
        return _result(None, ["Attachment format is unsupported; provide PDF, PPTX or a text export."])
    try:
        data = _read_attachment(path, expected_stat)
        return _extract_pptx(data, limit) if extension == ".pptx" else _extract_pdf(data, limit)
    except ValueError as error:
        return _result(None, [str(error)])
    except (OSError, zipfile.BadZipFile, ET.ParseError, UnicodeDecodeError,
            RuntimeError, zlib.error, EOFError, NotImplementedError):
        return _result(None, ["Attachment is malformed, inaccessible or changed; provide a text export."])


def _worker() -> None:
    # Isolated interpreter startup keeps submission PYTHONPATH/user-site modules
    # out of the parser. Its input is bytes already validated by the collector.
    data = sys.stdin.buffer.read(MAX_INPUT_BYTES + 1)
    limit = max(0, min(int(sys.argv[2]), MAX_TEXT_CHARS))
    if len(data) > MAX_INPUT_BYTES:
        result = _result(None, ["PDF exceeds the 10 MiB input limit."])
    else:
        result = _extract_pdf_data(data, limit)
    sys.stdout.buffer.write(json.dumps(result, ensure_ascii=False).encode("utf-8"))


if __name__ == "__main__" and len(sys.argv) == 3 and sys.argv[1] == "--pdf-worker":
    _worker()
